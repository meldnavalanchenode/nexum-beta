// Change-event reports — the document a team hands to someone else.
//
// WHY THIS EXISTS. Everything in a change cycle was already recorded: the
// baseline, the detected changes, what the team predicted, what Nexum planned,
// what was actually checked, and who recorded each result. It was recorded in
// five different files, which means the only way to tell someone what happened
// was to send them a folder and let them reconstruct it.
//
// That is a real problem for a beta. `ledger/CHANGE-EVENT-001.md` asks a team
// to write this summary BY HAND, after doing the work, at the end of a late
// night — which is exactly when nobody writes anything. A report they can
// generate in one command is a report that might actually get sent.
//
// WHAT IT MUST NOT DO. It renders what is on record and nothing else. It does
// not grade the team, does not decide whether Nexum helped, and does not
// upgrade a self-reported change into an observation. Where the record says
// UNKNOWN or says nobody ruled, the document says so too — a summary that
// quietly rounded UNKNOWN up to fine would be worse than no summary.
//
// CORE module: imports only core, no platform knowledge, no I/O of its own.

import { plan } from './planner.js'

const H = (s) => `## ${s}`
const nothing = '_nothing on record_'

/** Markdown list, or a stated absence — never an empty section. */
function list(items, empty = nothing) {
  const rows = (items ?? []).filter(Boolean)
  return rows.length ? rows.map((x) => `- ${x}`).join('\n') : empty
}

const stamp = (iso) => (typeof iso === 'string' ? iso.replace('T', ' ').slice(0, 16) + ' UTC' : '—')

/**
 * Render one change cycle as markdown.
 *
 * Every argument is data already on disk; this function reads nothing. Passing
 * a partial picture is allowed and produces a partial document that says which
 * parts are missing, because a team that skipped the prediction step still
 * deserves a record of what changed.
 */
export function renderCycle({
  experiment = null,
  fromState = null,
  toState = null,
  changes = [],
  reported = [],
  applicability = [],
  required = [],
  results = [],
  status = null,
  engineVersion = null,
  generatedAt = null,
} = {}) {
  const out = []
  const from = fromState?.version != null ? `V${fromState.version}` : (experiment?.baseline ?? '—')
  const to = toState?.version != null ? `V${toState.version}` : (experiment?.newState ?? 'not yet saved')
  const robot = toState?.declared?.configName ?? fromState?.declared?.configName ?? 'unnamed robot'

  out.push(`# Change event — ${from} → ${to}`)
  out.push('')
  out.push(`**Robot:** ${robot}  `)
  out.push(`**Baseline frozen:** ${stamp(fromState?.createdAt)}  `)
  out.push(`**New state saved:** ${stamp(toState?.createdAt)}  `)
  if (status) out.push(`**Status at the end of this cycle:** ${status}  `)
  if (engineVersion) out.push(`**Engine:** v${engineVersion}  `)
  if (generatedAt) out.push(`**Report generated:** ${stamp(generatedAt)}`)
  out.push('')
  out.push('Generated by Nexum from its own records. Nothing here is a judgement about')
  out.push('the team or the robot — it is what was recorded, including what was not.')
  out.push('')

  // ── what changed ─────────────────────────────────────────────────────────
  out.push(H('What changed'))
  out.push('')
  out.push('Detected by comparing files and reports against the baseline.')
  out.push('')
  out.push(list(changes.map((c) => {
    const d = [c.previous, c.current].filter((x) => x != null)
    const span = d.length === 2 ? ` — ${c.previous} → ${c.current}` : ''
    return `\`${c.kind}\` **${c.component}**${span}`
  }), '_no file-detectable change_'))
  out.push('')

  // Self-reported changes are kept visually separate, permanently. Merging them
  // into the list above would let a person's word read as a measurement.
  out.push(H('Reported by a person (not detected)'))
  out.push('')
  out.push('Nothing was measured for these. They are on record as somebody\'s word, with their name.')
  out.push('')
  out.push(list(reported.map((r) =>
    `**${r.component}** — reported by ${r.by ?? 'unnamed'}${r.note ? `: "${r.note}"` : ''} _(${r.at ? stamp(r.at) : 'no timestamp'})_`
  ), '_none reported_'))
  out.push('')

  // ── what stopped counting ────────────────────────────────────────────────
  out.push(H('What stopped counting'))
  out.push('')
  out.push('Historical results never change. This is whether each one still describes the robot as it is now.')
  out.push('')
  const order = { REVALIDATE: 0, UNKNOWN: 1, 'RE-DERIVED': 2, APPLICABLE: 3 }
  const rows = [...applicability].sort(
    (a, b) => (order[a.applicability] ?? 9) - (order[b.applicability] ?? 9))
  if (!rows.length) {
    out.push(nothing)
  } else {
    out.push('| Evidence | Recorded | Still applies? | Why |')
    out.push('|---|---|---|---|')
    for (const r of rows) {
      const why = (r.reason ?? '').replace(/\|/g, '\\|')
      const codes = r.reasonCodes?.length ? ` \`[${r.reasonCodes.join(', ')}]\`` : ''
      out.push(`| \`${r.evidenceId}\` | ${r.result ?? '—'} | **${r.applicability}** | ${why}${codes} |`)
    }
  }
  out.push('')

  out.push(H('Checks Nexum asked for'))
  out.push('')
  out.push('The minimum set, ordered so an upstream failure makes later checks moot.')
  out.push('')
  out.push(list(required.map((q, i) =>
    `**${i + 1}. ${q.action ?? q.label ?? 'check'}**${q.reasonCode ? ` \`[${q.reasonCode}]\`` : ''}` +
    (q.because ? `  \n   ${q.because}` : '')
  ), '_none owed — either nothing was reached, or this run re-established it_'))
  out.push('')

  // ── what was actually done ───────────────────────────────────────────────
  out.push(H('What was actually checked'))
  out.push('')
  if (!results.length) {
    out.push('_no results recorded during this cycle_')
  } else {
    out.push('| Test | Verdict | Recorded by | When |')
    out.push('|---|---|---|---|')
    for (const r of results) {
      // The ledger spells these recordedBy / recordedAt. An earlier version read
      // `by`/`at` and printed "unnamed" over results that carried a real name —
      // for a tool whose whole claim is provenance, that is the worst possible
      // field-name slip, so both spellings are accepted.
      const who = r.recordedBy ?? r.by ?? 'unnamed'
      const when = r.recordedAt ?? r.at
      const bar = r.threshold != null ? ` (bar ${JSON.stringify(r.threshold)})` : ''
      const val = r.value != null ? ` ${r.value}` : ''
      out.push(`| \`${r.testId ?? r.test ?? '—'}\` | ${r.verdict ?? '—'}${val}${bar} | ${who} | ${stamp(when)} |`)
    }
  }
  out.push('')

  // ── the experiment ───────────────────────────────────────────────────────
  out.push(H('Team plan vs Nexum plan'))
  out.push('')
  if (!experiment) {
    out.push('_no prediction was recorded for this cycle, so there is nothing to compare._')
    out.push('')
    out.push('This is a real gap rather than a formatting one: without a prediction made')
    out.push('*before* Nexum\'s answer was visible, there is no way to tell whether Nexum')
    out.push('named anything the team had not already thought of.')
  } else {
    const d = experiment.debrief?.deltas ?? {}
    out.push(`Prediction by **${experiment.predictedBy ?? 'unnamed'}** at ${stamp(experiment.predictedAt)}, ` +
             `locked before Nexum's answer was revealed at ${stamp(experiment.revealedAt)}.`)
    out.push('')
    out.push('| | |')
    out.push('|---|---|')
    out.push(`| Team predicted | ${(experiment.prediction?.checks ?? []).join(', ') || '—'} |`)
    out.push(`| Actually checked | ${(experiment.debrief?.actualChecks ?? []).join(', ') || '—'} |`)
    out.push(`| Both named it | ${(d.agreed ?? []).join(', ') || '—'} |`)
    out.push(`| Nexum added, beyond the prediction | ${(d.nexumAddedBeyondPrediction ?? []).join(', ') || '—'} |`)
    out.push(`| …of which were performed | ${(d.usefulAdditions ?? []).join(', ') || '—'} |`)
    out.push(`| Team named, Nexum did not | ${(d.predictionBeyondNexum ?? []).join(', ') || '—'} |`)
    out.push(`| Recommended, not performed | ${(d.recommendedNotPerformed ?? []).join(', ') || '—'} |`)
    out.push('')
    if (experiment.verdict) {
      out.push(`**Verdict (assigned by ${experiment.verdict.by ?? 'unnamed'}):** ${experiment.verdict.verdict}`)
      if (experiment.verdict.basis) out.push(`  \n_${experiment.verdict.basis}_`)
    } else {
      out.push('**Verdict: not yet assigned.** Nexum does not grade itself — whether this')
      out.push('helped is a human\'s call, recorded with `nexum verdict`.')
    }
    if (experiment.debrief?.notes) {
      out.push('')
      out.push(`> ${experiment.debrief.notes}`)
    }
  }
  out.push('')

  // ── what is still unknown ────────────────────────────────────────────────
  out.push(H('What is still unknown'))
  out.push('')
  const unknowns = []
  const cov = toState?.coverage ?? fromState?.coverage ?? {}
  for (const [k, v] of Object.entries(cov)) {
    if (v === false) unknowns.push(`\`${k}\` — no data was supplied, so nothing was established either way`)
  }
  for (const r of applicability) {
    if (r.applicability === 'UNKNOWN') {
      unknowns.push(`\`${r.evidenceId}\` — a proposed rule links it, but nobody has ruled on that rule`)
    }
  }
  for (const r of results) {
    if (r.verdict === 'UNKNOWN') unknowns.push(`\`${r.testId ?? r.test}\` — recorded by ${r.recordedBy ?? r.by ?? 'someone unnamed'}, but no threshold says what would count as passing`)
  }
  out.push(list(unknowns, '_nothing outstanding on record_'))
  out.push('')

  // ── integrity ────────────────────────────────────────────────────────────
  out.push(H('Record'))
  out.push('')
  if (fromState?.stateDigest) out.push(`- ${from} digest \`${String(fromState.stateDigest).slice(0, 16)}…\``)
  if (toState?.stateDigest) out.push(`- ${to} digest \`${String(toState.stateDigest).slice(0, 16)}…\``)
  out.push('- States are append-only and digest-protected; this report does not modify them.')
  out.push('- The digest proves the record was not edited. It does not prove the record was accurate.')
  out.push('')

  return out.join('\n')
}

/**
 * Diff two SAVED states. Purpose-built rather than reusing detectChanges,
 * which compares a saved state against a freshly-read candidate and needs the
 * raw config XML to do it — a saved state keeps only the digest. Handing it a
 * synthesized configXml would have produced a fabricated `config-changed`
 * record, so this reads only fields a state actually stores.
 *
 * Every row it emits is therefore a recorded fact about the two records, not a
 * re-measurement of the robot.
 */
export function diffStates(from, to) {
  if (!from || !to) return []
  const out = []
  const a = from.declared ?? {}, b = to.declared ?? {}

  if (a.configName != null && b.configName != null && a.configName !== b.configName) {
    out.push({ kind: 'config-renamed', component: 'configuration', previous: a.configName, current: b.configName })
  } else if (a.configSha256 && b.configSha256 && a.configSha256 !== b.configSha256) {
    out.push({
      kind: 'config-changed', component: 'configuration',
      previous: String(a.configSha256).slice(0, 12) + '…',
      current: String(b.configSha256).slice(0, 12) + '…',
    })
  }

  const prev = new Map((a.devices ?? []).map((d) => [d.name, d]))
  const now = new Map((b.devices ?? []).map((d) => [d.name, d]))
  for (const [name, d] of now) {
    const was = prev.get(name)
    if (!was) {
      out.push({ kind: 'device-added', component: `device "${name}"`, previous: '(absent)', current: `${d.type} port ${d.port}` })
      continue
    }
    if (was.type !== d.type) {
      out.push({ kind: 'device-type-changed', component: `device "${name}"`, previous: was.type, current: d.type })
    }
    if (String(was.port) !== String(d.port) || String(was.bus ?? '') !== String(d.bus ?? '')) {
      out.push({ kind: 'device-port-moved', component: `device "${name}"`, previous: `port ${was.port}`, current: `port ${d.port}` })
    }
  }
  for (const [name, d] of prev) {
    if (!now.has(name)) {
      out.push({ kind: 'device-removed', component: `device "${name}"`, previous: `${d.type} port ${d.port}`, current: '(absent)' })
    }
  }

  if (a.codeDigest && b.codeDigest && a.codeDigest !== b.codeDigest) {
    out.push({
      kind: 'software-changed', component: 'software',
      previous: String(a.codeDigest).slice(0, 12) + '…',
      current: String(b.codeDigest).slice(0, 12) + '…',
    })
  }
  return out
}

/**
 * Applicability and the revalidation plan for a historical state pair.
 *
 * This lives here rather than in the CLI because `bin/` is forbidden from
 * orchestrating — `test/failclosed.test.js` fails the build on a bare
 * `plan({…})` there, and it is right to: the CLI and the web UI each grew their
 * own copy of the live pipeline once and drifted in three places. A report over
 * two SAVED states is a different question from assessing current inputs, so it
 * does not belong in assess() either; it belongs next to the renderer that
 * consumes it.
 *
 * Takes the graph as an argument rather than loading it: this module does no
 * I/O, which is what keeps it testable without a filesystem.
 */
export function cycleApplicability({ fromState, changes = [], graph }) {
  if (!fromState || !graph) return { applicability: [], required: [] }
  try {
    const planned = plan({ state: fromState, changes, graph })
    return { applicability: planned.applicability ?? [], required: planned.required ?? [] }
  } catch {
    // A partial document beats refusing to write one — the sections that do not
    // depend on the plan are still worth handing to someone.
    return { applicability: [], required: [] }
  }
}
